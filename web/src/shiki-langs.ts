// shiki/langs (vite.config.ts points it here). Shiki has 200-odd grammars,
// and the hub carries the web app inside its binary, so it carries these:
// what agents write most. Every other language shiki knows is here too, as
// plain text, so no file stops a diff from drawing. Only the page resolves
// languages; the worker is handed them (vite.config.ts gives it none).
